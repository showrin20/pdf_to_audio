// Reads .env and generates src/lib/env.generated.js so the extension
// (which has no filesystem/.env access at runtime) can bundle the key as a
// plain JS fallback. Re-run this (npm run sync-env) whenever .env changes.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const envPath = path.join(root, ".env");
const outPath = path.join(root, "src/lib/env.generated.js");

function parseEnv(text) {
  const vars = {};
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

const vars = existsSync(envPath) ? parseEnv(readFileSync(envPath, "utf8")) : {};

const banner = `// AUTO-GENERATED by scripts/sync-env.mjs from .env — do not edit by hand.\n// Re-run \`npm run sync-env\` after changing .env.\n`;
const body =
  `export const GEMINI_API_KEY = ${JSON.stringify(vars.GEMINI_API_KEY || "")};\n` +
  `export const GEMINI_MODEL = ${JSON.stringify(vars.GEMINI_MODEL || "")};\n`;

writeFileSync(outPath, banner + body);
console.log(`Wrote ${path.relative(root, outPath)} from .env`);
